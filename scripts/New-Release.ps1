<#
.SYNOPSIS
    Builds toaster.exe for the version in CMakeLists.txt and publishes it as a GitHub release.

.DESCRIPTION
    Steps:
      1. Reads the version from project(toaster VERSION x.y.z) in CMakeLists.txt.
      2. Checks that the working tree is clean, you are on main, main matches
         origin/main and the tag v<version> does not exist yet.
      3. Configures (preset msvc-x64), builds Release and runs the tests.
      4. Checks that 'toaster --version' prints the same version.
      5. Writes to dist\:
           toaster-<version>-win-x64.zip     (toaster.exe, README.md, LICENSE)
           toaster.exe
           SHA256SUMS.txt
      6. Creates the annotated tag v<version>, pushes it and creates the GitHub
         release with these files (GitHub CLI 'gh', signed in).

    Whatever is in the sounds/images folders of the preset gets embedded, so run
    Get-SoundPacks.ps1 / Get-Images.ps1 first if you want them in the release.

.PARAMETER Draft
    Create the GitHub release as a draft.

.PARAMETER LocalOnly
    Build and package into dist\ only: no tag, no push, no GitHub release.
    The git checks are relaxed (a dirty tree or another branch is only a warning).

.PARAMETER SkipTests
    Do not run ctest.

.PARAMETER Notes
    Release notes. Default: notes generated by GitHub from the commits since the last release.

.EXAMPLE
    .\scripts\New-Release.ps1
    Builds, tags v0.3.0 and publishes the release.

.EXAMPLE
    .\scripts\New-Release.ps1 -LocalOnly
    Only builds the release files into dist\.
#>
[CmdletBinding()]
param(
    [switch] $Draft,
    [switch] $LocalOnly,
    [switch] $SkipTests,
    [string] $Notes
)

Set-StrictMode -Version 3.0
$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$preset = 'msvc-x64'
$buildDir = Join-Path $root "build\$preset"
$distDir = Join-Path $root 'dist'

function Invoke-Checked([string] $Exe, [string[]] $Arguments) {
    Write-Host "> $Exe $($Arguments -join ' ')" -ForegroundColor DarkGray
    & $Exe @Arguments
    if ($LASTEXITCODE -ne 0) { throw "'$Exe $($Arguments -join ' ')' failed with exit code $LASTEXITCODE" }
}

function Get-GitOutput([string[]] $Arguments) {
    $output = & git -C $root @Arguments
    if ($LASTEXITCODE -ne 0) { throw "git $($Arguments -join ' ') failed" }
    ($output | Out-String).Trim()
}

function Stop-OrWarn([string] $Message) {
    if ($LocalOnly) { Write-Warning $Message } else { throw $Message }
}

# --- 1. version ----------------------------------------------------------------
$cmakeLists = [IO.File]::ReadAllText((Join-Path $root 'CMakeLists.txt'))
$match = [regex]::Match($cmakeLists, 'project\s*\(\s*toaster\b[^)]*?\bVERSION\s+(\d+\.\d+\.\d+)')
if (-not $match.Success) { throw 'Could not find project(toaster VERSION x.y.z) in CMakeLists.txt' }
$version = $match.Groups[1].Value
$tag = "v$version"
Write-Host "Releasing toaster $version ($tag)" -ForegroundColor Cyan

# --- 2. git checks -------------------------------------------------------------
foreach ($tool in @('git', 'cmake', 'ctest') + $(if ($LocalOnly) { @() } else { @('gh') })) {
    if (-not (Get-Command $tool -ErrorAction SilentlyContinue)) {
        throw "'$tool' is not on PATH. Run this from a Developer PowerShell for VS$(if ($tool -eq 'gh') { '; install the GitHub CLI: winget install GitHub.cli' })."
    }
}
if (-not $LocalOnly) {
    & gh auth status *> $null
    if ($LASTEXITCODE -ne 0) { throw "GitHub CLI is not signed in. Run 'gh auth login' first." }
}

if (Get-GitOutput @('status', '--porcelain')) {
    Stop-OrWarn 'The working tree has uncommitted changes. Commit or stash them first.'
}
$branch = Get-GitOutput @('rev-parse', '--abbrev-ref', 'HEAD')
if ($branch -ne 'main') { Stop-OrWarn "You are on '$branch', not main." }

if (-not $LocalOnly) {
    Invoke-Checked git @('-C', $root, 'fetch', '--quiet', '--tags', 'origin', 'main')
    $head = Get-GitOutput @('rev-parse', 'HEAD')
    $remote = Get-GitOutput @('rev-parse', 'origin/main')
    if ($head -ne $remote) { throw 'main differs from origin/main. Pull and/or push first.' }

    & git -C $root rev-parse -q --verify "refs/tags/$tag" *> $null
    if ($LASTEXITCODE -eq 0) { throw "Tag $tag already exists. Bump the version in CMakeLists.txt first." }
}

# --- 3. build and test ---------------------------------------------------------
Push-Location $root
try {
    Invoke-Checked cmake @('--preset', $preset)
    Invoke-Checked cmake @('--build', '--preset', 'release')
    if (-not $SkipTests) {
        Invoke-Checked ctest @('--preset', 'release')
    }
}
finally {
    Pop-Location
}

$exe = Join-Path $buildDir 'Release\toaster.exe'
if (-not (Test-Path -LiteralPath $exe)) { throw "Build output not found: $exe" }

# --- 4. version check ----------------------------------------------------------
$reported = (& $exe --version | Out-String).Trim()
if ($reported -ne "toaster $version") {
    throw "toaster.exe reports '$reported', expected 'toaster $version'. Re-run CMake configure."
}

# --- 5. package ----------------------------------------------------------------
$packageName = "toaster-$version-win-x64"
$stage = Join-Path $distDir $packageName
$zip = Join-Path $distDir "$packageName.zip"
$looseExe = Join-Path $distDir 'toaster.exe'
$sums = Join-Path $distDir 'SHA256SUMS.txt'

if (Test-Path -LiteralPath $distDir) { Remove-Item -LiteralPath $distDir -Recurse -Force }
New-Item -ItemType Directory -Path $stage -Force | Out-Null
Copy-Item -LiteralPath $exe -Destination $stage
Copy-Item -LiteralPath (Join-Path $root 'README.md') -Destination $stage
Copy-Item -LiteralPath (Join-Path $root 'LICENSE') -Destination $stage
Compress-Archive -Path (Join-Path $stage '*') -DestinationPath $zip -CompressionLevel Optimal
Copy-Item -LiteralPath $exe -Destination $looseExe
Remove-Item -LiteralPath $stage -Recurse -Force

$assets = @($zip, $looseExe)
($assets | ForEach-Object {
    '{0}  {1}' -f (Get-FileHash -LiteralPath $_ -Algorithm SHA256).Hash.ToLowerInvariant(), (Split-Path -Leaf $_)
}) -join "`n" | Set-Content -LiteralPath $sums -Encoding ascii -NoNewline
$assets += $sums

$size = [math]::Round((Get-Item -LiteralPath $looseExe).Length / 1MB, 1)
Write-Host "Packaged in $distDir (toaster.exe: $size MB)" -ForegroundColor Green
$assets | ForEach-Object { Write-Host "  $(Split-Path -Leaf $_)" }

if ($LocalOnly) {
    Write-Host 'LocalOnly: no tag, no push, no GitHub release.'
    return
}

# --- 6. tag and GitHub release -------------------------------------------------
Invoke-Checked git @('-C', $root, 'tag', '-a', $tag, '-m', "toaster $version")
Invoke-Checked git @('-C', $root, 'push', 'origin', $tag)

$releaseArgs = @('release', 'create', $tag) + $assets + @('--title', "toaster $version", '--verify-tag')
if ($Notes) { $releaseArgs += @('--notes', $Notes) } else { $releaseArgs += '--generate-notes' }
if ($Draft) { $releaseArgs += '--draft' }
Push-Location $root
try {
    Invoke-Checked gh $releaseArgs
}
finally {
    Pop-Location
}

Write-Host "Released toaster $version." -ForegroundColor Green
